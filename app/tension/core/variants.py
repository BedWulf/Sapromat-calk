def get_variant_data(number):
    if not 1 <= number <= 30:
        raise ValueError('Номер варианта должен быть от 1 до 30')
    return P_VALUES[number-1], Q_VALUES[number-1]

def get_preset_scheme(number, l):
    support, entries = SCHEMES[number]
    result = [[] for _ in range(4)]
    for entry in entries:
        kind, count, direction, a, *rest = entry
        seg = min(int(a), 3)
        if kind == 'F':
            result[seg].append({'type':'force', 'count':count, 'direction':direction,
                                'position': a*l, 'segment':seg})
        else:
            b = rest[0]
            result[seg].append({'type':'distributed', 'count':count, 'direction':direction,
                                'start': a*l, 'end':b*l, 'segment':seg})
    return support, result
